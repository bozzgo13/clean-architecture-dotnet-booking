using MediatR;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using MyBookingApi.Application.Common.Interfaces;
using MyBookingApi.Domain.Entities;
using MyBookingApi.Domain.Enums;

namespace MyBookingApi.Application.Auth.Commands.Bootstrap;

/// <summary>
/// The outcome of an administrator bootstrap attempt. The command reports its result instead of
/// throwing, so "the account already exists" can be treated as success (idempotency).
/// </summary>
public enum AdminBootstrapResult
{
    /// <summary>A brand-new administrator account was created.</summary>
    Created,

    /// <summary>An account with the same email already existed, so nothing was changed.</summary>
    AlreadyExists,

    /// <summary>An administrator already exists, so the first-run provisioning was refused.</summary>
    SkippedBecauseAdminExists
}

/// <summary>
/// Represents a CQRS Command that provisions the first administrator account of a fresh deployment.
///
/// It is deliberately kept separate from <c>RegisterCommand</c>: the public registration path must stay
/// locked to <see cref="UserRole.User"/> so it can never be used to self-assign the administrator role
/// (privilege escalation). It is also idempotent, so it is safe to invoke on every startup and from
/// every replica: re-running it against a database that already holds the account is a no-op.
/// </summary>
/// <param name="Email">The administrator's email address. Stored normalized (trimmed and lowercased).</param>
/// <param name="Password">The one-time password. Generated by the caller in memory, never read from configuration.</param>
/// <param name="FirstName">The administrator's first name.</param>
/// <param name="LastName">The administrator's last name.</param>
public record BootstrapAdminUserCommand(
    string Email,
    string Password,
    string FirstName,
    string LastName
) : IRequest<AdminBootstrapResult>;

/// <summary>
/// Handles the execution of the <see cref="BootstrapAdminUserCommand"/>. It provisions the first
/// administrator only when none exists yet, hashing the credential and persisting a
/// <see cref="User"/> with <see cref="UserRole.Admin"/>.
/// </summary>
public class BootstrapAdminUserCommandHandler : IRequestHandler<BootstrapAdminUserCommand, AdminBootstrapResult>
{
    private readonly IApplicationDbContext _context;
    private readonly IPasswordHasher _passwordHasher;
    private readonly ILogger<BootstrapAdminUserCommandHandler> _logger;

    /// <summary>
    /// Initializes a new instance of the <see cref="BootstrapAdminUserCommandHandler"/> class.
    /// </summary>
    /// <param name="context">The database context abstraction accessed via Dependency Injection.</param>
    /// <param name="passwordHasher">The password hashing service used to secure the one-time credential.</param>
    /// <param name="logger">The structured logger used for security-relevant audit events.</param>
    public BootstrapAdminUserCommandHandler(
        IApplicationDbContext context,
        IPasswordHasher passwordHasher,
        ILogger<BootstrapAdminUserCommandHandler> logger)
    {
        _context = context;
        _passwordHasher = passwordHasher;
        _logger = logger;
    }

    /// <summary>
    /// Provisions the initial administrator asynchronously.
    /// </summary>
    /// <param name="request">The command carrying the account details.</param>
    /// <param name="cancellationToken">A token to observe while waiting for asynchronous operations to complete.</param>
    /// <returns>The outcome of the attempt; never throws for an already provisioned account.</returns>
    public async Task<AdminBootstrapResult> Handle(
        BootstrapAdminUserCommand request,
        CancellationToken cancellationToken)
    {
        // Normalize up front so the uniqueness check matches the value that will be persisted.
        var normalizedEmail = User.NormalizeEmail(request.Email);

        // Idempotency by identity: the account already exists, so there is nothing to do. This makes
        // the command safe to run on every deployment and from every replica.
        if (await _context.Users.AnyAsync(u => u.Email == normalizedEmail, cancellationToken))
        {
            _logger.LogInformation(
                "Admin bootstrap skipped: the account already exists. Email={Email}", normalizedEmail);

            return AdminBootstrapResult.AlreadyExists;
        }

        // Defense in depth: only ever provision the FIRST administrator. Once any administrator exists
        // this code path becomes inert, so a leftover bootstrap configuration cannot mint new admins.
        if (await _context.Users.AnyAsync(u => u.Role == UserRole.Admin, cancellationToken))
        {
            _logger.LogWarning("Admin bootstrap refused: an administrator already exists.");

            return AdminBootstrapResult.SkippedBecauseAdminExists;
        }

        // Hash the credential before it ever reaches the domain entity or the database.
        var passwordHash = _passwordHasher.HashPassword(request.Password);

        // Instantiate the User entity using Rich Domain Model principles: the constructor normalizes the
        // email and enforces the core invariants.
        var admin = new User(
            normalizedEmail,
            passwordHash,
            request.FirstName,
            request.LastName,
            UserRole.Admin);

        _context.Users.Add(admin);

        try
        {
            await _context.SaveChangesAsync(cancellationToken);
        }
        catch (DbUpdateException exception) when (IsUniqueConstraintViolation(exception))
        {
            // The existence check above and this INSERT are not atomic: two replicas launched at the
            // same time can both pass the check and then race to the database, where the unique index on
            // Users.Email rejects the loser. The desired end state (exactly one administrator) was
            // reached, so it is reported as success rather than surfaced as a startup failure.
            _logger.LogInformation(
                "Admin bootstrap converged: the account was provisioned concurrently. Email={Email}",
                normalizedEmail);

            return AdminBootstrapResult.AlreadyExists;
        }

        // Audit-relevant security event, recorded at Warning so it stands out in production logs.
        // Only the opaque identifier and the email are recorded; the credential is never logged.
        _logger.LogWarning(
            "Initial administrator account provisioned. UserId={UserId} Email={Email}",
            admin.Id,
            normalizedEmail);

        return AdminBootstrapResult.Created;
    }

    /// <summary>
    /// Determines whether a <see cref="DbUpdateException"/> was caused by a uniqueness conflict
    /// (a duplicate value hitting a unique index), rather than some other database failure.
    /// </summary>
    /// <param name="exception">The exception raised by Entity Framework Core.</param>
    /// <returns><c>true</c> when the underlying error indicates a unique-constraint violation.</returns>
    private static bool IsUniqueConstraintViolation(DbUpdateException exception)
    {
        // Provider-agnostic check: SQL Server reports duplicate-key (2601) and unique-constraint (2627)
        // violations using messages that contain "duplicate"/"unique", and other relational providers do
        // the same. Email is the only unique index on Users, so matching these keywords is sufficient.
        var innerException = exception.InnerException;
        if (innerException is null)
        {
            return false;
        }

        return innerException.Message.Contains("duplicate", StringComparison.OrdinalIgnoreCase)
            || innerException.Message.Contains("unique", StringComparison.OrdinalIgnoreCase);
    }
}
